// Clean URL routing for every guide page while preserving legacy root hash routes.
const starberrySeoRoutes = {
  welcome: "/",
  rules: "/rules/",
  links: "/links/",
  faq: "/faq/",
  join: "/join/",
  "getting-started": "/getting-started/",
  claims: "/claims/",
  commands: "/commands/",
  "server-info": "/server-info/",
  cosmetics: "/cosmetics/",
  farming: "/farming/",
  mining: "/mining/",
  foraging: "/foraging/",
  fishing: "/fishing/",
  skills: "/skills/",
  crops: "/crops/",
  food: "/food/",
  economy: "/economy/",
  events: "/events/",
  supporter: "/ranks/",
  changelog: "/changelog/"
};

const starberryPathRoutes = Object.fromEntries(
  Object.entries(starberrySeoRoutes).map(([id, path]) => [path, id])
);

function starberryPageUrl(id) {
  return starberrySeoRoutes[id] || `/#${id}`;
}

function starberryIsKnownPage(id) {
  if (starberrySeoRoutes[id]) return true;
  if (typeof state === "undefined" || !state.navigation) return false;
  return state.navigation.groups.some(group => group.pages.some(page => page.id === id));
}

function starberryNormalizedPath() {
  let path = window.location.pathname || "/";
  if (!path.endsWith("/")) path += "/";
  return path;
}

currentId = function() {
  const path = starberryNormalizedPath();
  const hashId = window.location.hash.replace("#", "");

  // A real clean page path always wins. This keeps section anchors on pages
  // such as /rules/#community-conduct from being mistaken for page routes.
  if (path !== "/" && starberryPathRoutes[path]) {
    return starberryPathRoutes[path];
  }

  // Legacy root links such as /#getting-started remain supported.
  if (hashId && starberryIsKnownPage(hashId)) {
    return hashId;
  }

  if (starberryPathRoutes[path]) return starberryPathRoutes[path];
  return "welcome";
};

renderNav = function() {
  const nav = document.getElementById("nav");
  nav.innerHTML = state.navigation.groups.map(group => `
    <div class="nav-group">
      <div class="nav-group-title">✦ ${group.title} ✦</div>
      ${group.pages.map(page => `
        <a class="nav-link" data-page="${page.id}" href="${starberryPageUrl(page.id)}">
          <span class="nav-icon">${page.icon}</span>
          <span>${page.label}</span>
        </a>
      `).join("")}
    </div>
  `).join("");
};

// Legacy #page links generated by older content are upgraded to clean URLs.
// The right-side TOC is excluded because those hashes point to sections on the current page.
document.addEventListener("click", event => {
  const anchor = event.target.closest("a[href^='#']");
  if (!anchor || anchor.closest("#toc")) return;
  const id = (anchor.getAttribute("href") || "").slice(1);
  if (!id || !starberryIsKnownPage(id)) return;
  event.preventDefault();
  window.location.href = starberryPageUrl(id);
}, true);
